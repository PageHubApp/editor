// Usage: node packages/engine/scripts/gen-patterns.mjs <patterns.json>
// Writes patternData.ts (the library) and patternSlugs.ts (slugs only, cheap to import) beside it.
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const out = new URL("../src/kits/tailwind/patterns/", import.meta.url);
const slim = src.map(({ title, slug, mode, colors, maxStroke, maxScale, maxSpacing, width, height, vHeight, path }) => ({ title, slug, mode, colors, maxStroke, maxScale, maxSpacing, width, height, vHeight, path }));
const header = "// Generated by packages/engine/scripts/gen-patterns.mjs from the Pattern Monster library (MIT, see LICENSE.md). Do not edit.\n";

writeFileSync(new URL("patternData.ts", out), `${header}import type { PatternDef } from "./patternSvg.js";\n\nexport const PATTERNS: readonly PatternDef[] = [\n${slim.map((p) => "  " + JSON.stringify(p) + ",").join("\n")}\n];\n`);
writeFileSync(new URL("patternSlugs.ts", out), `${header}export const PATTERN_SLUGS: readonly string[] = ${JSON.stringify(slim.map((p) => p.slug))};\n`);
console.log(slim.length, "patterns");
